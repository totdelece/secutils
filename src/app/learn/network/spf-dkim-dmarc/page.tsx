          <tr>
            <td><strong>SPF</strong></td>
            <td>送信元<strong>IPアドレス</strong>が、そのドメインの許可リストに載っているか</td>
            <td>DNSのTXTレコード</td>
            <td>転送されるとIPが変わり失敗する</td>
          </tr>
          <tr>
            <td><strong>DKIM</strong></td>
            <td>メールに付いた<strong>電子署名</strong>が正しいか（改ざんされていないか）</td>
